import { deriveRuleSlug } from "../../src/site-routes.js";

const routeKinds = ["products", "release-lines", "rules"] as const;
type RouteKind = (typeof routeKinds)[number];
type RouteRecord = { id: string; slug: string };

export function routeAliases(
  records: Record<RouteKind, readonly RouteRecord[]>,
  redirects: Readonly<Record<string, string>>,
): Map<string, string[]> {
  const routes = new Map<string, { collection: RouteKind; aliases: string[] }>();
  for (const collection of routeKinds) {
    for (const { id, slug } of records[collection]) {
      const aliases = collection === "rules" && id !== slug ? [`/rules/${id}/`] : [];
      routes.set(slug, { collection, aliases });
    }
  }
  for (const oldSlug of Object.keys(redirects).sort()) {
    let target = oldSlug;
    const visited = new Set<string>();
    while (Object.hasOwn(redirects, target)) {
      if (visited.has(target)) throw new Error(`Redirect cycle from ${oldSlug}.`);
      visited.add(target);
      target = redirects[target]!;
    }
    const route = routes.get(target);
    if (!route) continue;
    if (routes.has(oldSlug)) throw new Error(`Redirect ${oldSlug} replaces a canonical slug.`);
    route.aliases.push(`/${route.collection}/${oldSlug}/`);
  }
  return new Map([...routes].filter(([, { aliases }]) => aliases.length).map(([slug, { aliases }]) => [slug, aliases]));
}

export function publicRuleRoutesSource(records: readonly RouteRecord[], version: string): string {
  const groups = new Map<string, string[]>();
  for (const { id, slug } of [...records].sort((a, b) => (a.id < b.id ? -1 : 1))) {
    const parts = id.split(".");
    const prefix = parts.slice(0, Math.min(2, parts.length - 1)).join(".");
    const suffix = prefix ? id.slice(prefix.length + 1) : id;
    const entries = groups.get(prefix) ?? [];
    entries.push(slug === deriveRuleSlug(id) ? suffix : `${suffix}:${slug}`);
    groups.set(prefix, entries);
  }
  return [
    `// Generated by site-data from the verified Ebb ${version} snapshot and locked slugs.`,
    "// Each row starts with a shared ID prefix, then rule suffixes with optional :slug overrides.",
    "export const publicRuleRoutes: string = `" + [...groups].map((group) => group.flat().join(" ")).join("\n") + "`;",
    "",
  ].join("\n");
}
